SELECT
  e.ID AS ENTITY_ID,
  e.NAME AS ENTITY_NAME,
  e.REGION,
  e.CATEGORY,
  e.STATUS,
  COUNT(*) AS EVENT_COUNT,
  SUM(CASE WHEN f.KPI_AVG_BRENT <= (SELECT T FROM thresh) THEN 1 ELSE 0 END) AS ALERT_COUNT,
  ROUND(AVG(f.KPI_AVG_BRENT), 2) AS AVG_BRENT,
  ROUND(AVG(f.KPI_TAPIS_PREMIUM), 2) AS AVG_TAPIS_PREMIUM,
  ROUND(AVG(f.KPI_STORAGE_CONTANGO), 2) AS AVG_STORAGE_CONTANGO
FROM RAW.PRICE_FEEDS f
JOIN RAW.MARKET_REPORTS e ON e.ID = f.ENTITY_ID
CROSS JOIN thresh
GROUP BY e.ID, e.NAME, e.REGION, e.CATEGORY, e.STATUS;

